def _descriptor(  # noqa: PLR0913, PLR0917 - catalog rows keep every risk field visible
    identifier: str,
    name: str,
    version: str,
    executable: tuple[str, ...],
    license_expression: str,
    source: str,
    release: str,
    predicates: tuple[str, ...],
    capabilities: tuple[str, ...],
    network: str,
    parser: str,
    media: tuple[str, ...],
    argv: tuple[str, ...],
    *,
    admission: AdapterAdmission = AdapterAdmission.PROMOTED,
    effect: str = "mutate",
    platforms: tuple[str, ...] = _ALL_PLATFORMS,
    bounds: ResourceBounds = _PROCESS_LIMITS,
    environment: tuple[tuple[str, str], ...] = (),
    accepted_result_exit_codes: tuple[int, ...] = (0,),
    output_source: OutputSource = OutputSource.WORKSPACE_FILE,
    ruleset_pin: str | None = None,
    config_pin: str | None = None,
    limitations: tuple[str, ...] = (),
    legal_note: str | None = None,
    transport: AdapterTransport = AdapterTransport.PROCESS,
) -> AdapterDescriptor:
    return AdapterDescriptor(
        identifier=identifier,
        tool_name=name,
        tool_version=version,
        executable_names=executable,
        executable_digest_policy="runtime-sha256-required",
        license_expression=license_expression,
        source_url=source,
        release_url=release,
        platforms=platforms,
        target_predicates=predicates,
        capabilities=capabilities,
        required_effect=effect,
        network_requirement=network,
        transport=transport,
        parser_id=parser,
        parser_version="0.1.0",
        output_media_types=media,
        output_source=output_source,
        argv_template=argv,
        environment=environment,
        accepted_result_exit_codes=accepted_result_exit_codes,
        bounds=bounds,
        admission=admission,
        provenance=(source, release),
        limitations=(
            "Tool output is an unverified assertion, never a SOVA finding.",
            "The descriptor does not install, sandbox, or legally authorize the tool.",
            *limitations,
        ),
        ruleset_pin=ruleset_pin,
        config_pin=config_pin,
        legal_note=legal_note,
    )


