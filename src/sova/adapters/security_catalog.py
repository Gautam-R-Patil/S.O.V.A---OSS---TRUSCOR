_BY_ID = {descriptor.identifier: descriptor for descriptor in _CATALOG}
if len(_BY_ID) != len(_CATALOG):  # pragma: no cover - import-time catalog invariant
    raise RuntimeError("duplicate security adapter identifier")  # noqa: TRY003


def security_adapter_catalog() -> tuple[AdapterDescriptor, ...]:
    """Return the immutable catalog in stable identifier order."""
    return tuple(sorted(_CATALOG, key=lambda item: item.identifier))


def promoted_security_adapters() -> tuple[AdapterDescriptor, ...]:
    return tuple(
        descriptor
        for descriptor in security_adapter_catalog()
        if descriptor.admission == AdapterAdmission.PROMOTED
    )


def get_security_adapter(identifier: str) -> AdapterDescriptor:
    try:
        return _BY_ID[identifier]
    except KeyError as error:
        raise FormatError(
            "SOVA-ADAPTER-UNKNOWN",
            "security adapter is not present in the curated catalog",
            details={"id": identifier},
        ) from error


def assert_catalog_ids(expected: Iterable[str]) -> None:
    """Compatibility assertion used by methodology and contribution tooling."""
    missing = sorted(set(expected) - set(_BY_ID))
    if missing:
        raise FormatError(
            "SOVA-ADAPTER-CATALOG-PARITY",
            "required adapters are missing",
            details={"missing": missing},
        )


